const assert = require('node:assert/strict');
const {numeric, matrix, pasteRows} = require('../web/earnings-view.js');

assert.equal(numeric('0'), 0);
assert.equal(numeric(''), null);
assert.equal(numeric('—'), null);
assert.equal(numeric('1,234.5'), 1234.5);
assert.equal(numeric('(1,234.5)'), -1234.5);
assert.equal(numeric('−0.5'), -0.5);
for (const input of ['=1+2', '12,34', '1.2.3', 'Infinity', '1e999']) assert.throws(() => numeric(input));
const keys = ['year', 'quarter', 'revenue', 'operatingIncome', 'eps'];
const pasted = matrix('회계연도\t분기\t매출\t영업이익\tEPS\r\n2026\tQ2\t1,000\t(10)\t0\r\n2026\tQ3\t1200\t\t1.25\r\n');
assert.equal(pasted.length, 2);
const original = [{year: 2025, quarter: 4, revenue: '500', operatingIncome: '50', eps: '.5'}];
const rows = pasteRows(original, pasted, 1, 0, keys);
assert.equal(rows.length, 3);
assert.equal(rows[1].revenue, '1,000');
assert.equal(rows[1].eps, '0');
assert.equal(rows[2].operatingIncome, '');
assert.equal(original.length, 1, 'Pasting must not mutate the original table');
const amountOnly = pasteRows(rows, matrix('800\t0\t-.2\n900\t10\t.3'), 1, 2, keys);
assert.equal(amountOnly[1].year, '2026');
assert.equal(amountOnly[1].quarter, 'Q2');
assert.equal(amountOnly[1].revenue, '800');
assert.equal(amountOnly[2].eps, '.3');
assert.throws(() => pasteRows(rows, [['extra', 'column']], 0, 4, keys));
assert.throws(() => pasteRows(rows, [['2026']], 100, 0, keys));
assert.equal(matrix('2026\tQ3\t0\t\t\n').length, 1);
assert.equal(matrix('FY2026\tQ3\t0').length, 1, 'A fiscal year value is not a header');
console.log('Editable table numeric and paste checks passed.');
